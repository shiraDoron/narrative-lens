def _get(all_results, author, variant, field):
    return all_results.get(author, {}).get(variant, {}).get(field)


def _print_analysis(all_results):
    print("\n" + "=" * 100)
    print("ANALYSIS (exploratory evidence only - NOT validated/confirmed; the masking-policy "
          "hypothesis was derived from an audit of this SAME IDF test set)")
    print("=" * 100)

    selective_variants = (
        "sbert_person_masked_aug", "sbert_person_misc_masked_aug",
        "sbert_person_masked_aug_soft_topic", "sbert_person_misc_masked_aug_soft_topic",
    )

    orig_bernie_r = _get(all_results, "BernieSanders", "sbert_original", "recall_true_narrative")
    orig_bernie_rw = _get(all_results, "BernieSanders", "sbert_original", "pct_misclassified_right_wing")
    orig_idf_r = _get(all_results, "IDF", "sbert_original", "recall_true_narrative")
    full_idf_r = _get(all_results, "IDF", "sbert_full_masked_aug", "recall_true_narrative")
    orig_maria_r = _get(all_results, "MariaZakharova", "sbert_original", "recall_true_narrative")
    dup_bernie_r = _get(all_results, "BernieSanders", "sbert_duplicated_original_control", "recall_true_narrative")
    dup_bernie_rw = _get(all_results, "BernieSanders", "sbert_duplicated_original_control", "pct_misclassified_right_wing")

    full_idf_cost = (orig_idf_r - full_idf_r) if None not in (orig_idf_r, full_idf_r) else None

    print("\nPer-variant check against the pre-registered, multi-condition success pattern "
          "(a variant only 'interesting' if ALL conditions hold):")
    for variant in selective_variants:
        bernie_r = _get(all_results, "BernieSanders", variant, "recall_true_narrative")
        bernie_rw = _get(all_results, "BernieSanders", variant, "pct_misclassified_right_wing")
        idf_r = _get(all_results, "IDF", variant, "recall_true_narrative")
        maria_r = _get(all_results, "MariaZakharova", variant, "recall_true_narrative")
        if None in (bernie_r, bernie_rw, idf_r, maria_r, orig_bernie_r, orig_bernie_rw,
                    orig_idf_r, orig_maria_r, full_idf_cost, dup_bernie_r, dup_bernie_rw):
            print(f"   {variant}: missing data, skipped.")
            continue
        idf_cost = orig_idf_r - idf_r
        cond_a = bernie_r > orig_bernie_r
        cond_b = bernie_rw < orig_bernie_rw
        cond_c = idf_cost < full_idf_cost
        cond_d = (orig_maria_r - maria_r) <= 0.05  # no large drop - 5pp tolerance, not a hard win requirement
        cond_e = not (bernie_r <= dup_bernie_r and bernie_rw >= dup_bernie_rw)  # not fully explained by duplication alone
        print(f"\n   {variant}:")
        print(f"     (a) Bernie recall {bernie_r*100:.1f}% > original {orig_bernie_r*100:.1f}%? {cond_a}")
        print(f"     (b) Bernie->RW {bernie_rw*100:.1f}% < original {orig_bernie_rw*100:.1f}%? {cond_b}")
        print(f"     (c) IDF cost {idf_cost*100:.1f}pp < full-masking cost {full_idf_cost*100:.1f}pp? {cond_c}")
        print(f"     (d) Maria recall {maria_r*100:.1f}% within 5pp of original {orig_maria_r*100:.1f}%? {cond_d}")
        print(f"     (e) not fully explained by duplicated-original control alone? {cond_e}")
        interesting = all((cond_a, cond_b, cond_c, cond_d, cond_e))
        print(f"     => ALL conditions met (exploratory 'interesting' pattern)? {interesting}")

    print("\nReminder: any 'interesting' result above is EXPLORATORY EVIDENCE for the "
          "selective-masking hypothesis, not a validated or confirmed finding - the policy was "
          "chosen using this same IDF test set's error patterns. A genuinely confirmatory test "
          "requires fresh held-out authors never used for hypothesis generation in Sections 19-24.")


