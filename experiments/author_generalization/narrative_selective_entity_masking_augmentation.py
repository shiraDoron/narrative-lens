# =========================================================================================
# Verification step (run BEFORE any training, per explicit instruction): prove that
# PERSON-only masking touches ONLY PER spans, and PERSON+MISC masking touches ONLY PER+MISC
# spans, leaving ORG/LOC substrings byte-identical to the original text.
# =========================================================================================
def masked_text_for_policy(text, raw_entities, types_to_mask):
    filtered = [e for e in raw_entities if e["entity_group"] in types_to_mask]
    return mask_entities(text, filtered)


def verify_selective_masking():
    print("\n" + "=" * 100)
    print("VERIFYING selective masking isolates entity types correctly (before any training)")
    print("=" * 100)
    examples = [
        "As part of IDF activities in Lebanon, IDF special forces operated overnight in an "
        "attempt to locate findings related the missing navigator Ron Arad.",
        "In response to yesterday's events in which Druze civilians were attacked, the IDF "
        "struck a command center used by Hezbollah, belonging to the Syrian regime in "
        "southern Syria.",
    ]
    ner_analyzer = EntityAnalysisPipeline()
    all_ok = True
    for text in examples:
        raw_entities = ner_analyzer.extract_raw_entities(text)
        raw_entities = reconstruct_fragmented_entities(raw_entities, text)
        print(f"\nOriginal text: {text}")
        print(f"Entities found: {[(e['text'], e['entity_group']) for e in raw_entities]}")

        full_masked = mask_entities(text, raw_entities)
        person_masked = masked_text_for_policy(text, raw_entities, {"PER"})
        person_misc_masked = masked_text_for_policy(text, raw_entities, {"PER", "MISC"})
        print(f"  full masked:         {full_masked}")
        print(f"  person-only masked:  {person_masked}")
        print(f"  person+misc masked:  {person_misc_masked}")

        for ent in raw_entities:
            span = text[ent["start"]:ent["end"]]
            # PERSON-only policy: every non-PER span's original characters must survive
            # untouched in the person-masked output.
            if ent["entity_group"] != "PER" and span not in person_masked:
                print(f"  [FAIL] PERSON-only masking altered a non-PER span: '{span}' "
                      f"({ent['entity_group']}) not found intact in person-masked output.")
                all_ok = False
            # PERSON+MISC policy: every ORG/LOC span's original characters must survive
            # untouched in the person+misc-masked output.
            if ent["entity_group"] not in ("PER", "MISC") and span not in person_misc_masked:
                print(f"  [FAIL] PERSON+MISC masking altered an ORG/LOC span: '{span}' "
                      f"({ent['entity_group']}) not found intact in person+misc-masked output.")
                all_ok = False
    if all_ok:
        print("\n[OK] PERSON-only masking leaves ORG/LOC/MISC spans byte-identical to the "
              "original text; PERSON+MISC masking leaves ORG/LOC spans byte-identical to the "
              "original text, on all examples checked above.")
    else:
        print("\n[FAIL] Selective masking did NOT isolate entity types correctly - see [FAIL] "
              "lines above. Do not proceed to training until this is fixed.")
    return all_ok


# =========================================================================================
# Step 1: build (once) or load a text -> RAW (type-annotated) entity list over the FULL
# corpus. Unlike section 21's cache, this stores raw entities (not already-masked text), so
# any masking policy (including future ones) can be derived from it without re-running NER.
# =========================================================================================
def build_or_load_raw_entities_cache():
    if os.path.exists(RAW_ENTITIES_CACHE_FILE):
        print(f"Found existing raw-entities cache '{RAW_ENTITIES_CACHE_FILE}'. Loading...")
        return torch.load(RAW_ENTITIES_CACHE_FILE, weights_only=False)

    print("\n=== Building fresh raw-entities cache over the FULL corpus (one-time, reused by "
          "all policies/authors) ===")
    df = load_raw_data()
    texts = df["text"].astype(str).str.slice(0, 3000)
    unique_texts = texts.unique().tolist()
    print(f"  {len(unique_texts)} unique texts (of {len(texts)} total rows) to run NER on...")

    print("Loading BERT-NER model (dslim/bert-base-NER) for entity-span extraction...")
    ner_analyzer = EntityAnalysisPipeline()

    raw_entities_by_text = {}
    for i, text in enumerate(unique_texts):
        raw_entities = ner_analyzer.extract_raw_entities(text)
        raw_entities = reconstruct_fragmented_entities(raw_entities, text)
        raw_entities_by_text[text] = raw_entities
        if (i + 1) % 1000 == 0:
            print(f"    ...{i + 1}/{len(unique_texts)} texts processed")

    result = {"raw_entities_by_text": raw_entities_by_text, "n_unique_texts": len(unique_texts)}
    os.makedirs(CACHE_DIR, exist_ok=True)
    torch.save(result, RAW_ENTITIES_CACHE_FILE)
    print(f"Saved raw-entities cache to '{RAW_ENTITIES_CACHE_FILE}'.")
    return result


# =========================================================================================
# Step 2: per-author, per-policy feature cache (train/val only - test is never masked in
# this experiment, so masked test embeddings are never needed): masked-SBERT embeddings
# (fresh, policy-specific) + soft_dense (reused by position from the existing ablation_loao
# cache) + label.
# =========================================================================================
def build_or_load_policy_author_cache(policy_name, author, raw_entities_by_text):
    cache_file = POLICY_CACHE_TEMPLATE.format(policy=policy_name, author=author)
    if os.path.exists(cache_file):
        print(f"Found existing '{policy_name}' feature cache '{cache_file}'. Loading...")
        return torch.load(cache_file, weights_only=False)

    print(f"\n=== Building fresh '{policy_name}'-masked feature cache for held-out author "
          f"'{author}' (train/val only) ===")
    types_to_mask = MASK_POLICIES[policy_name]
    df = load_raw_data()
    train_data, val_data, _test_data = split_leave_one_author(df, author)
    for split_df in (train_data, val_data):
        split_df["text"] = split_df["text"].astype(str).str.slice(0, 3000)
    splits = {"train": train_data, "val": val_data}

    existing_cache_path = ORIGINAL_CACHE_TEMPLATE.format(author=author)
    existing_cache = torch.load(existing_cache_path, weights_only=False)

    print(f"Loading SBERT model '{BERTOPIC_EMBEDDING_MODEL_NAME}' (frozen, encode-only)...")
    sbert_model = SentenceTransformer(BERTOPIC_EMBEDDING_MODEL_NAME)

    result = {}
    sbert_dim = None
    n_missing_entities_entry = 0
    for name, split_df in splits.items():
        cached_labels = [label for _, label in existing_cache[name]]
        fresh_labels = split_df["label"].astype(int).tolist()
        if cached_labels != fresh_labels or len(cached_labels) != len(split_df):
            raise RuntimeError(
                f"Alignment check FAILED for split '{name}' (author='{author}'): the existing "
                f"'{existing_cache_path}' no longer matches a fresh load_raw_data()+"
                f"split_leave_one_author() reconstruction. Refusing to silently reuse "
                f"misaligned features."
            )

        print(f"--- Split '{name}' ({len(split_df)} rows), policy='{policy_name}' "
              f"(masking {sorted(types_to_mask)}) ---")
        texts = split_df["text"].tolist()
        labels = split_df["label"].astype(int).tolist()

        masked_texts = []
        for t in texts:
            if t in raw_entities_by_text:
                masked_texts.append(masked_text_for_policy(t, raw_entities_by_text[t], types_to_mask))
            else:
                n_missing_entities_entry += 1
                masked_texts.append(t)  # fall back to the original (unmasked) text

        print(f"  Computing SBERT embeddings on '{policy_name}'-masked text...")
        sbert_embeddings = sbert_model.encode(masked_texts, convert_to_numpy=True, show_progress_bar=True)
        sbert_dim = int(sbert_embeddings.shape[1])

        rows = []
        for i in range(len(texts)):
            base_feat, base_label = existing_cache[name][i]
            assert base_label == labels[i], f"label mismatch at split={name} idx={i}"
            feat = {
                "sbert_embedding": torch.tensor(sbert_embeddings[i], dtype=torch.float32),
                "soft_dense": base_feat["soft_dense"],
            }
            rows.append((feat, labels[i]))
        result[name] = rows

    if n_missing_entities_entry:
        print(f"[!] WARNING: {n_missing_entities_entry} row(s) had no entry in the raw-entities "
              f"cache (fell back to unmasked text).")

    result["_meta"] = {
        "bertopic_vec_size": existing_cache["_meta"]["bertopic_vec_size"],
        "sbert_dim": sbert_dim,
        "policy": policy_name,
        "types_masked": sorted(types_to_mask),
        "reused_soft_dense_from": existing_cache_path,
        "n_missing_entities_entry": n_missing_entities_entry,
    }
    os.makedirs(CACHE_DIR, exist_ok=True)
    torch.save(result, cache_file)
    print(f"Saved new '{policy_name}' feature cache to '{cache_file}'.")
    return result


